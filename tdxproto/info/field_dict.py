def _t_code(official_num: int) -> str:
    """官方编号 → T 编码（T + 补零三位）。"""
    return f"T{official_num - 1:03d}"


def balance_sheet_fields() -> dict[str, str]:
    """资产负债表 T 编码 → 中文名。官方编号 8-73 → T007-T072。"""
    return {_t_code(n): name for n, name in _OFFICIAL.items() if 8 <= n <= 73}


def income_statement_fields() -> dict[str, str]:
    """利润表 T 编码 → 中文名。官方编号 74-97 → T073-T096。"""
    return {_t_code(n): name for n, name in _OFFICIAL.items() if 74 <= n <= 97}


def cashflow_fields() -> dict[str, str]:
    """现金流量表 T 编码 → 中文名。

    现金流表 T 编号 = 官方编号 - 90（已用 StockClient.finance() 交叉验证）。
    例: 官方98=销售商品收到现金 → T008; 官方107=经营现金流净额 → T017。
    """
    return {
        f"T{n - 90:03d}": name
        for n, name in _OFFICIAL.items()
        if 98 <= n <= 133
    }


