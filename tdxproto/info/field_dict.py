def translate_row(row: dict, field_map: dict[str, str]) -> dict[str, Any]:
    """将原始 T/拼音编码行翻译为可读字段名行。未映射的键保留原名。"""
    out: dict[str, Any] = {}
    for k, v in row.items():
        out[field_map.get(k, k)] = v
    return out
